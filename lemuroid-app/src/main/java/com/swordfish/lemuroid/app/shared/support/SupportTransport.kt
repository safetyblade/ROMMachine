package com.swordfish.lemuroid.app.shared.support

import android.app.Activity
import android.content.ClipData
import android.content.ClipboardManager
import android.content.Context
import android.content.Intent
import android.net.Uri
import androidx.core.content.FileProvider
import java.io.File
import java.net.URLEncoder

object SupportTransport {
    const val EMAIL = "safetybladegaming@gmail.com"

    fun copy(
        context: Context,
        report: SupportReport,
    ) {
        context.getSystemService(ClipboardManager::class.java)
            .setPrimaryClip(ClipData.newPlainText("CARTDECK diagnostic report", report.text))
    }

    fun share(
        activity: Activity,
        report: SupportReport,
        file: File,
        email: Boolean,
    ) {
        check(!email || hasEmailApp(activity)) { "No compatible email app" }
        val intent = shareIntent(activity, report, file, email)
        activity.startActivity(
            Intent.createChooser(intent, if (email) "Open email draft" else "Share diagnostic report"),
        )
    }

    internal fun shareIntent(
        context: Context,
        report: SupportReport,
        file: File,
        email: Boolean,
    ): Intent {
        val attachment = FileProvider.getUriForFile(context, "${context.packageName}.support", file)
        return Intent(Intent.ACTION_SEND).apply {
            type = "application/zip"
            putExtra(Intent.EXTRA_STREAM, attachment)
            clipData = ClipData.newRawUri(report.packageName, attachment)
            addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
            if (email) {
                putExtra(Intent.EXTRA_EMAIL, arrayOf(EMAIL))
                putExtra(Intent.EXTRA_SUBJECT, subject(report))
                putExtra(Intent.EXTRA_TEXT, body(report))
                // Match apps that can handle email composition, while delivering the SEND attachment.
                selector = Intent(Intent.ACTION_SENDTO, Uri.parse("mailto:"))
            }
        }
    }

    private fun hasEmailApp(activity: Activity): Boolean =
        Intent(Intent.ACTION_SENDTO, Uri.parse("mailto:")).resolveActivity(activity.packageManager) != null

    fun textEmail(
        activity: Activity,
        report: SupportReport,
    ) {
        check(hasEmailApp(activity)) { "No compatible email app" }
        val subject = URLEncoder.encode(subject(report), "UTF-8").replace("+", "%20")
        val body = URLEncoder.encode(body(report, includeAttachment = false), "UTF-8").replace("+", "%20")
        activity.startActivity(Intent(Intent.ACTION_SENDTO, Uri.parse("mailto:$EMAIL?subject=$subject&body=$body")))
    }

    private fun subject(report: SupportReport): String =
        "[CARTDECK BUG] ${report["console"]} | ${report["game"]} | ${report["category"]} | ${report["versionCode"]}"
            .replace('\n', ' ').take(240)

    private fun body(
        report: SupportReport,
        includeAttachment: Boolean = true,
    ): String =
        buildString {
            appendLine("CARTDECK SUPPORT REPORT")
            appendLine("Report ID: ${report.id}")
            appendLine("Report category: ${report["category"]}")
            appendLine("Game: ${report["game"]}")
            appendLine("Console: ${report["console"]}")
            appendLine("Engine: ${report["engine"]}")
            appendLine("Application version: ${report["version"]}")
            appendLine("Application build: ${report["versionCode"]} · ${report["buildRevision"]}")
            appendLine("Device: ${report["manufacturer"]} ${report["deviceModel"]}")
            appendLine("\nPLAYER DESCRIPTION\n${report["description"]}")
            appendLine("\nTECHNICAL SUMMARY")
            appendLine("GPU: ${report.diagnosticValue("GL_RENDERER", "graphics")}")
            appendLine("Failure: ${report.diagnosticValue("failure").substringBefore(';')}")
            appendLine("Process exit reason: ${report.diagnosticValue("androidProcessExit")}")
            appendLine("Last verified stage: ${report.diagnosticValue("lastVerifiedStage", "stage")}")
            appendLine("Engine version: ${report.diagnosticValue("selectedEngineVersion")}")
            appendLine("Host version: ${report.diagnosticValue("host_build", "host").take(200)}")
            appendLine("Recovery status: ${report.diagnosticValue("startupRecovery")}")
            appendLine("Save status: ${report.diagnosticValue("saveWrite")}")
            if (includeAttachment) appendLine("\nDIAGNOSTIC ATTACHMENT\n${report.packageName}")
            appendLine("\nGenerated by CARTDECK Support.")
        }
}
