package com.swordfish.lemuroid.app.shared.library

import android.content.Context
import android.util.AtomicFile
import com.swordfish.lemuroid.app.mobile.feature.shelf.ShelfStore
import com.swordfish.lemuroid.app.mobile.feature.shelf.retiredShelfKey
import com.swordfish.lemuroid.app.mobile.feature.shelf.shelfGameKey
import com.swordfish.lemuroid.lib.library.db.entity.Game
import com.swordfish.lemuroid.lib.library.db.entity.RetiredCartridge
import org.json.JSONObject
import java.io.File

/** Write-ahead identity map. Room is atomic; shelf replay derives truth from committed Room. */
internal class LibraryRefreshJournal(context: Context) {
    private val file = File(context.filesDir, "cartdeck/library-refresh-v1.json")
    private val atomic = AtomicFile(file)

    fun pending(): Boolean = file.exists() || File(file.path + ".bak").exists()

    fun prepare(games: List<Game>, retired: List<RetiredCartridge> = emptyList()) {
        check(!pending()) { "Previous refresh requires recovery" }
        file.parentFile!!.mkdirs()
        val identities = JSONObject()
        retired.forEach { identities.put(it.cartridgeId, retiredShelfKey(it.cartridgeId)) }
        games.forEach {
            check(!identities.has(it.cartridgeId)) { "Live cartridge conflicts with retired identity" }
            identities.put(it.cartridgeId, shelfGameKey(it.systemId, it.fileUri))
        }
        val stream = atomic.startWrite()
        try {
            stream.write(
                JSONObject().put("version", 1).put("identities", identities).toString().toByteArray(Charsets.UTF_8),
            )
            atomic.finishWrite(stream)
        } catch (error: Throwable) {
            atomic.failWrite(stream)
            throw error
        }
    }

    /**
     * Explicit owner choice. The normal refresh journal remains v1 compatible:
     * a manual plan only permits removal of a second, untouched autogenerated
     * candidate shelf cell AFTER Room has committed the retired UUID rebinding.
     */
    fun prepareManualRecovery(
        games: List<Game>,
        retired: List<RetiredCartridge>,
        cartridgeId: String,
        candidateKey: String,
    ) {
        require(retired.any { it.cartridgeId == cartridgeId })
        require(games.any { shelfGameKey(it.systemId, it.fileUri) == candidateKey })
        prepare(games, retired)
        val root = JSONObject(atomic.openRead().bufferedReader().use { it.readText() })
        root.put(
            "manualRecovery",
            JSONObject().put("retiredKey", retiredShelfKey(cartridgeId)).put("candidateKey", candidateKey),
        )
        val stream = atomic.startWrite()
        try {
            stream.write(root.toString().toByteArray(Charsets.UTF_8))
            atomic.finishWrite(stream)
        } catch (error: Throwable) {
            atomic.failWrite(stream)
            throw error
        }
    }

    suspend fun reconcile(
        games: List<Game>,
        shelf: ShelfStore,
        retired: List<RetiredCartridge> = emptyList(),
    ) {
        if (!pending()) return
        val root = atomic.openRead().bufferedReader().use { JSONObject(it.readText()) }
        require(root.getInt("version") == 1) { "Unknown refresh journal version" }
        val identities = root.getJSONObject("identities")
        // An unavailable slot has a distinct UUID key. A different cartridge
        // arriving at the same historical URI must never hijack that slot.
        val currentKeys =
            retired.associate { it.cartridgeId to retiredShelfKey(it.cartridgeId) } +
                games.associate { it.cartridgeId to shelfGameKey(it.systemId, it.fileUri) }
        val moves =
            currentKeys.mapNotNull { (cartridgeId, current) ->
                val old = identities.optString(cartridgeId).takeIf { it.isNotEmpty() } ?: return@mapNotNull null
                if (old == current) null else old to current
            }.toMap()
        val names = games.associate { shelfGameKey(it.systemId, it.fileUri) to it.displayName() }
        val unavailable = retired.map { retiredShelfKey(it.cartridgeId) }.toSet()
        val manual = root.optJSONObject("manualRecovery")
        val manualOld = manual?.optString("retiredKey")
        val manualNew = manual?.optString("candidateKey")
        shelf.update { layout ->
            val known = layout.sections.flatMap { it.cells }.mapNotNull { it.gameKey }.toSet()
            // Only the explicitly approved identity move may retire an
            // untouched, default candidate shelf cell. No other conflict is
            // resolved by guessing ownership or deleting layout.
            val mergeCandidate =
                manualOld != null && manualNew != null &&
                    moves[manualOld] == manualNew && manualOld in known && manualNew in known
            if (mergeCandidate) {
                val matches =
                    layout.sections.flatMap { section ->
                        section.cells.filter { it.gameKey == manualNew }.map { section to it }
                    }
                check(matches.size == 1) { "Selected source has ambiguous shelf placement" }
                val (section, cell) = matches.single()
                check(
                    section.id == com.swordfish.lemuroid.app.mobile.feature.shelf.ShelfLayout.UNSORTED &&
                        cell.id == "game:$manualNew" &&
                        cell.facing == com.swordfish.lemuroid.app.mobile.feature.shelf.CartridgeFacing.SPINE,
                ) { "Selected source shelf was customised; recovery requires a separate review" }
            }
            check(
                moves.none { (old, new) ->
                    old in known && new in known && !(mergeCandidate && old == manualOld && new == manualNew)
                },
            ) { "Ambiguous shelf identity move" }
            layout.copy(
                sections =
                    layout.sections.map { section ->
                        section.copy(
                            cells =
                                section.cells
                                    .filterNot { cell ->
                                        mergeCandidate && section.id ==
                                            com.swordfish.lemuroid.app.mobile.feature.shelf.ShelfLayout.UNSORTED &&
                                            cell.gameKey == manualNew && cell.id == "game:$manualNew"
                                    }
                                    .map { cell -> cell.copy(gameKey = moves[cell.gameKey] ?: cell.gameKey) },
                        )
                    },
            ).reconcile(names, removeMissing = true, retainedUnavailableKeys = unavailable)
        }
        // Replay after a crash between shelf write and delete is idempotent.
        atomic.delete()
        check(!pending()) { "Could not complete refresh journal" }
    }
}
